def emaki_phase(x):
    yy = y(x)
    if yy is None:
        return "Emaki, undated"
    if yy < 1185:
        return "Heian emaki (to 1185)"
    if yy < 1333:
        return "Kamakura emaki (1185–1333)"
    if yy < 1573:
        return "Muromachi emaki (1333–1573)"
    return "Edo emaki and later copies"


